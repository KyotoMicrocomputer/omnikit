//! The module containing infrastructure for subclassing the interfaces provided
//! by the Omnisight API.
//!
//! # Async Methods
//!
//! `[tag:api_rs_subclass_future]`
//! Some subclassing traits (`*Impl`) provide both `*_async` and `*_future`
//! versions of async methods. The `*_async` versions provide default
//! implementations to call `*_future` in a spawned task. Implementors have two
//! options:
//!
//! - Only implement `*_future`.
//! - Implement `*_async` with real code and `*_future` with stub code.
//!
//! The `*_future` methods are never cancelled synchronously. Some of them can
//! support asynchronous cancellation by using a provided [`gio::Cancellable`].
//!
//! Panics generated by the `*_future` methods are escalated to `abort`.

